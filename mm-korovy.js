/* Мое_коровы — общий аккаунт для всех моих сайтов (mm-account.js): сохранение игры в облаке.
   Godot хранит сохранение (user://) в базе браузера «/userfs» (IndexedDB, хранилище FILE_DATA). Перед запуском игры
   модуль подтягивает из аккаунта более свежее сохранение (index.html ждёт MMAccount.whenReady), а потом раз в минуту,
   при сворачивании и после входа отправляет своё. Если во время игры пришло сохранение с другого устройства —
   появляется полоса «Обновить». Кнопка 👤 в левом нижнем углу — вход, регистрация и выход.
   Важно: при новом экспорте из Godot файл index.html создаётся заново. Чтобы аккаунт остался, в настройках экспорта
   Web → HTML → Head Include вставьте:  <script src="mm-account.js"></script><script src="mm-korovy.js"></script>
   (без ожидания перед запуском сохранение с другого устройства придёт через полосу «Обновить»). */
window.MM_GAME_STARTED = false;
MMAccount.setup({
    app: 'korovy',
    title: 'Мое_коровы',
    fab: true,
    note: 'В аккаунте — сохранение игры (стадо, надои, улучшения).',
    idb: [{
        db: '/userfs', store: 'FILE_DATA', maxBytes: 3000000,
        // логи и кеши движка не нужны
        filter: function (key) { return !/\/(logs|shader_cache|vulkan|\.godot)\//.test(String(key)); }
    }],
    // во время игры движок держит своё сохранение в памяти и скоро перезапишет пришедшее — поэтому
    // останавливаем отправку (чтобы старое не ушло в аккаунт) и просим перезагрузить страницу
    onRemoteApplied: function () { if (window.MM_GAME_STARTED) { MMAccount.pause(); MMAccount.banner(); } }
});
